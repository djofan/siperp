import assert from "node:assert/strict";
import test from "node:test";
import { randomInt } from "node:crypto";
import { loadEnvConfig } from "@next/env";
import { participantInput, formatNip, type ParticipantModule } from "../modules/core/participant-policy";
import { cleanupParticipantFixtures, sequenceSnapshot, trackNumber } from "./helpers/participant-fixtures";
loadEnvConfig(process.cwd());
function form(values: Record<string, string>) { const data = new FormData(); for (const [key, value] of Object.entries(values)) data.set(key, value); return data; }
const phone = () => `08${randomInt(1000000000, 9999999999)}`;
test("format NIP berurutan dan validasi akun", () => {
  assert.equal(formatNip("teknisi", 1), "PTH01");
  assert.equal(formatNip("teknisi", 2), "PTH02");
  assert.equal(formatNip("teknisi", 100), "PTH100");
  assert.equal(formatNip("academy", 1), "PAZ001");
  assert.equal(formatNip("academy", 2), "PAZ002");
  assert.equal(formatNip("academy", 1000), "PAZ1000");
  const valid = { name: "Peserta Uji", address: "Alamat uji", phone: "081234567890", password: "Password-uji-2026", gender: "IKHWAN" };
  assert.equal(participantInput(form(valid), "academy").phone, "6281234567890");
  for (const invalid of [{ address: "" }, { gender: "GROUP_CUSTOM" }, { phone: "abc" }, { password: "pendek" }]) assert.throws(() => participantInput(form({ ...valid, ...invalid }), "academy"));
  assert.equal(participantInput(form({ ...valid, password: "" }), "academy", false).password, "");
});
test("NIP atomik, edit/hapus, satu teknisi per outlet, dan lingkup akses", async () => {
  const host = new URL(process.env.DATABASE_URL!).hostname;
  assert.ok(["localhost", "127.0.0.1", "[::1]"].includes(host), "Uji akun hanya di database lokal");
  const { prisma } = await import("../lib/prisma");
  const { createParticipantAccount, authenticateParticipant } = await import("../modules/core/participant-accounts");
  const { editParticipantAccount, deleteParticipantAccount } = await import("../modules/core/participant-management");
  const { allocateNip } = await import("../modules/core/participant-sequence");
  const { createTicket } = await import("../modules/teknisi/api/service");
  const users: string[] = [], outlets: string[] = [];
  const before = await sequenceSnapshot(prisma), issued = new Map<ParticipantModule, number>();
  const password = "Password-uji-2026";
  const base = { name: `Akun Uji ${Date.now()}`, address: "Alamat uji sementara", password };
  const register = async (slug: ParticipantModule, fields: Record<string, string>) => { const account = await createParticipantAccount(slug, form({ ...base, phone: phone(), ...fields })); users.push(account.userId); trackNumber(issued, slug, account.nip); return account; };
  try {
    const rollback = new Error("rollback-nip-test");
    await assert.rejects(prisma.$transaction(async tx => { const first = await allocateNip(tx, "academy"); const second = await allocateNip(tx, "academy"); assert.equal(Number(second.slice(3)), Number(first.slice(3)) + 1); throw rollback; }), error => error === rollback);
    assert.deepEqual(await sequenceSnapshot(prisma), before, "Counter harus ikut rollback transaksi");
    for (let i = 0; i < 3; i++) outlets.push((await prisma.teknisiOutlet.create({ data: { name: `${base.name} ${i}`, address: base.address, phone: "000" } })).id);
    const academyPhone = phone();
    const academy = await register("academy", { phone: academyPhone, gender: "AKHWAT" });
    const academy2 = await register("academy", { gender: "IKHWAN" });
    assert.equal(Number(academy2.nip.slice(3)), Number(academy.nip.slice(3)) + 1);
    const teknisiPhone = phone();
    const teknisi = await register("teknisi", { phone: teknisiPhone, outletId: outlets[0] });
    const second = await register("teknisi", { outletId: outlets[1] });
    assert.equal(Number(second.nip.slice(3)), Number(teknisi.nip.slice(3)) + 1);
    await assert.rejects(register("teknisi", { outletId: outlets[0] }), /sudah memiliki teknisi/);
    const races = await Promise.allSettled([register("teknisi", { outletId: outlets[2] }), register("teknisi", { outletId: outlets[2] })]);
    assert.equal(races.filter(result => result.status === "fulfilled").length, 1, "Satu teknisi saja pada pendaftaran bersamaan");
    for (const [slug, account] of [["academy", academy], ["teknisi", teknisi]] as const) {
      const session = await authenticateParticipant(slug, account.nip, password);
      assert.equal(session?.userId, account.userId); assert.equal(session?.isSuperadmin, false);
      assert.deepEqual(session?.moduleSlugs, slug === "teknisi" ? ["teknisi"] : []);
      assert.equal(await authenticateParticipant(slug, account.nip, "salah"), null);
      await prisma.user.update({ where: { id: account.userId }, data: { isActive: false } });
      assert.equal(await authenticateParticipant(slug, account.nip, password), null);
      await prisma.user.update({ where: { id: account.userId }, data: { isActive: true } });
    }
    assert.equal(await authenticateParticipant("academy", teknisi.nip, password), null);
    assert.equal(await authenticateParticipant("teknisi", academy.nip, password), null);
    const count = await prisma.user.count();
    await assert.rejects(register("academy", { phone: academyPhone, gender: "IKHWAN" }));
    assert.equal(await prisma.user.count(), count, "Duplikasi harus rollback akun Core");
    const profile = await prisma.zakatAcademyProfile.findUniqueOrThrow({ where: { userId: academy.userId } });
    await editParticipantAccount("academy", profile.id, form({ ...base, name: "Nama diperbarui", phone: academyPhone, gender: "IKHWAN", password: "" }));
    assert.equal((await authenticateParticipant("academy", academy.nip, password))?.name, "Nama diperbarui");
    assert.equal((await prisma.zakatAcademyProfile.findUniqueOrThrow({ where: { id: profile.id } })).gender, "IKHWAN");
    const newPassword = "Password-baru-2026";
    await editParticipantAccount("academy", profile.id, form({ ...base, phone: academyPhone, gender: "AKHWAT", password: newPassword }));
    assert.equal(await authenticateParticipant("academy", academy.nip, password), null);
    assert.ok(await authenticateParticipant("academy", academy.nip, newPassword));
    const techProfile = await prisma.teknisiParticipant.findUniqueOrThrow({ where: { userId: teknisi.userId } });
    const tech = await prisma.teknisiTechnician.findUniqueOrThrow({ where: { userId: teknisi.userId } });
    const techUser = { id: teknisi.userId, name: base.name, role: "technician", technician: tech, canManage: false, canWrite: true };
    const ticketForm = { outletId: outlets[0], customerName: "Pelanggan uji", customerPhone: "000", device: "HP uji", complaint: "Uji", priority: "normal", estimate: "0" };
    const ticket = await createTicket(techUser, form(ticketForm));
    assert.equal(ticket.outletId, outlets[0]); assert.equal(ticket.technicianId, tech.id);
    await assert.rejects(createTicket(techUser, form({ ...ticketForm, outletId: outlets[1] })), /outletnya sendiri/);
    await assert.rejects(editParticipantAccount("teknisi", techProfile.id, form({ ...base, phone: teknisiPhone, outletId: outlets[1], password: "" })), /sudah memiliki teknisi/);
    await deleteParticipantAccount("teknisi", techProfile.id);
    assert.equal(await authenticateParticipant("teknisi", teknisi.nip, password), null);
    assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: teknisi.userId } })).isActive, false);
    assert.equal((await prisma.teknisiTechnician.findUniqueOrThrow({ where: { id: tech.id } })).activeOutletId, null);
    assert.ok(await prisma.teknisiTicket.findUnique({ where: { id: ticket.id } }), "Riwayat servis tidak dihapus");
    const replacement = await register("teknisi", { outletId: outlets[0], phone: teknisiPhone });
    assert.ok(Number(replacement.nip.slice(3)) > Number(teknisi.nip.slice(3)), "NIP dihapus tidak boleh dipakai ulang");
    await deleteParticipantAccount("academy", profile.id);
    assert.equal(await authenticateParticipant("academy", academy.nip, newPassword), null);
    assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: academy.userId } })).isActive, false);
    assert.ok(await prisma.zakatAcademyProfile.findUnique({ where: { id: profile.id } }));
    const replacementAcademy = await register("academy", { phone: academyPhone, gender: "IKHWAN" });
    assert.ok(Number(replacementAcademy.nip.slice(3)) > Number(academy.nip.slice(3)));
  } finally { await cleanupParticipantFixtures(prisma, users, outlets, before, issued); await prisma.$disconnect(); }
});
